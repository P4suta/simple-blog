    let archive = Html::parse_document(body(&ja, "/archive/"));
    assert_eq!(texts(&archive, ".archive-year h2"), ["2026年"]);
    assert_eq!(texts(&archive, ".archive-list time"), ["9月3日"]);
    let home = Html::parse_document(body(&ja, "/"));
